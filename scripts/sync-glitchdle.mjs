// Rebuilds the Glitchdle catalogs (shared/riddle/catalogs/*.js) from public data:
// Wikidata (CC0) for what each item is, and the Stack Exchange API (CC BY-SA) for how many Stack
// Overflow questions it has. Three requests per category and one for the languages' counts,
// cached under node_modules/.cache, so a rerun the same day asks nothing. Review the diff before
// committing: players are graded on it.
//
//   node scripts/sync-glitchdle.mjs            fetch (or reuse the cache) and write the snapshots
//   node scripts/sync-glitchdle.mjs --fresh    ignore the cache
//   node scripts/sync-glitchdle.mjs --record   also save the raw answers as test fixtures

import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildCatalog, languageQuestions, resolveItems } from './glitchdle/normalize.js'
import { DATABASE_OVERRIDES, FRAMEWORK_OVERRIDES } from './glitchdle/overrides.js'
import { DATABASE_SEEDS, FRAMEWORK_SEEDS, LANGUAGE_TAGS } from './glitchdle/seeds.js'
import { fetchTagCounts, fetchWikidata } from './glitchdle/sources.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cacheDir = join(root, 'node_modules', '.cache', 'glitchdle-sync', new Date().toISOString().slice(0, 10))
const args = new Set(process.argv.slice(2))
if (args.has('--fresh')) await rm(cacheDir, { recursive: true, force: true })

const CATEGORIES = [
  { id: 'frameworks', exportName: 'FRAMEWORKS', seeds: FRAMEWORK_SEEDS, overrides: FRAMEWORK_OVERRIDES },
  { id: 'databases', exportName: 'DATABASES', seeds: DATABASE_SEEDS, overrides: DATABASE_OVERRIDES },
]

const thisYear = new Date().getUTCFullYear()

function snapshot({ id, exportName }, items) {
  const lines = items.map((item) => `  ${JSON.stringify(item)},`)
  return `// Generated by scripts/sync-glitchdle.mjs on ${today}. Don't edit by hand:
// fix scripts/glitchdle/overrides.js and run the sync again.
// Data: Wikidata (CC0) and Stack Overflow tag counts from the Stack Exchange API (CC BY-SA 4.0).
// ${items.length} ${id}, sorted by id. "questions" is the Stack Overflow count behind "popularity",
// "sitelinks" the number of Wikipedias behind "wikipedias".
export const ${exportName} = [
${lines.join('\n')}
]
`
}

// How the items spread over a ranked trait's buckets, to check the steps in shared/riddle/popularity.js.
const spread = (items, key) => Object.entries(Object.groupBy(items, (item) => item[key])).map(([bucket, list]) => `${bucket} ${list.length}`).join(', ')

const today = new Date().toISOString().slice(0, 10)
const languageCounts = await fetchTagCounts(Object.values(LANGUAGE_TAGS), { cacheDir })
const { questions, missing } = languageQuestions(LANGUAGE_TAGS, languageCounts)
if (missing.length) throw new Error(`No Stack Overflow count for ${missing.join(', ')}: fix LANGUAGE_TAGS in scripts/glitchdle/seeds.js`)
await writeFile(
  join(root, 'shared', 'riddle', 'catalogs', 'language-questions.js'),
  `// Generated by scripts/sync-glitchdle.mjs on ${today}. Don't edit by hand: run the sync again.
// Data: Stack Overflow tag counts from the Stack Exchange API (CC BY-SA 4.0), tags in
// scripts/glitchdle/seeds.js. shared/riddle/languages.js buckets them into "SO questions".
export const LANGUAGE_QUESTIONS = {
${Object.entries(questions)
  .map(([id, count]) => `  ${JSON.stringify(id)}: ${count},`)
  .join('\n')}
}
`,
)
console.log(`languages: ${Object.keys(questions).length} counts`)
if (args.has('--record')) {
  await mkdir(join(root, 'tests', 'fixtures', 'glitchdle'), { recursive: true })
  await writeFile(join(root, 'tests', 'fixtures', 'glitchdle', 'languages.raw.json'), JSON.stringify({ counts: languageCounts }))
}

for (const category of CATEGORIES) {
  const tags = category.seeds.map(([tag]) => tag)
  const { resolveRows, factRows } = await fetchWikidata(category.seeds, {
    cacheDir,
    ids: (rows) => [...new Set(Object.values(resolveItems(category.seeds, rows)))],
  })
  const counts = await fetchTagCounts(tags, { cacheDir })
  const { items, dropped } = buildCatalog({ categoryId: category.id, seeds: category.seeds, resolveRows, factRows, counts, overrides: category.overrides, thisYear })

  await writeFile(join(root, 'shared', 'riddle', 'catalogs', `${category.id}.js`), snapshot(category, items))
  console.log(`${category.id}: ${items.length} items, ${dropped.length} dropped`)
  console.log(`  popularity: ${spread(items, 'popularity')}; wikipedias: ${spread(items, 'wikipedias')}`)
  for (const { tag, reasons } of dropped) console.log(`  - ${tag}: ${reasons.join(', ')}`)

  if (args.has('--record')) {
    const dir = join(root, 'tests', 'fixtures', 'glitchdle')
    await mkdir(dir, { recursive: true })
    await writeFile(join(dir, `${category.id}.raw.json`), JSON.stringify({ resolveRows, factRows, counts }))
  }
}
